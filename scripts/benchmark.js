// EXPLAIN ANALYZE before/after composite index + N+1 vs JOIN latency.
// usage: npm run benchmark        (writes docs/benchmark-results.md)
require('dotenv').config();
const fs = require('fs'); const path = require('path');
const { pool, withTenant } = require('../src/config/db');

const SLUG = process.env.BENCH_TENANT || 'acme';
const RUNS = 7;
const Q = `SELECT id, customer_name, status, total, created_at FROM orders
           WHERE tenant_id = $1 AND created_at >= now() - interval '7 days'
           ORDER BY created_at DESC LIMIT 50`;
const median = (a) => [...a].sort((x, y) => x - y)[Math.floor(a.length / 2)];

async function explain(tenantId) {
  const times = []; let plan = '';
  for (let i = 0; i < RUNS; i++) {
    const rows = await withTenant(tenantId, async (db) =>
      (await db.query('EXPLAIN (ANALYZE, BUFFERS) ' + Q, [tenantId])).rows.map((r) => r['QUERY PLAN']));
    plan = rows.join('\n');
    times.push(parseFloat(plan.match(/Execution Time: ([\d.]+) ms/)[1]));
  }
  return { plan, median: median(times), min: Math.min(...times), times };
}

async function nPlusOne(tenantId, limit) {
  const t0 = process.hrtime.bigint(); let q = 0;
  await withTenant(tenantId, async (db) => {
    const { rows } = await db.query('SELECT id FROM orders WHERE tenant_id=$1 ORDER BY created_at DESC LIMIT $2', [tenantId, limit]); q++;
    for (const o of rows) { await db.query('SELECT oi.*, p.name FROM order_items oi JOIN products p ON p.id=oi.product_id WHERE oi.tenant_id=$1 AND oi.order_id=$2', [tenantId, o.id]); q++; }
  });
  return { ms: Number(process.hrtime.bigint() - t0) / 1e6, q };
}
async function joined(tenantId, limit) {
  const t0 = process.hrtime.bigint();
  await withTenant(tenantId, (db) => db.query(
    `SELECT o.id, json_agg(json_build_object('name', p.name, 'qty', oi.quantity)) items
     FROM (SELECT id, tenant_id FROM orders WHERE tenant_id=$1 ORDER BY created_at DESC LIMIT $2) o
     LEFT JOIN order_items oi ON oi.order_id=o.id AND oi.tenant_id=o.tenant_id
     LEFT JOIN products p ON p.id=oi.product_id GROUP BY o.id`, [tenantId, limit]));
  return { ms: Number(process.hrtime.bigint() - t0) / 1e6, q: 1 };
}

(async () => {
  const { rows: [t] } = await pool.query('SELECT id FROM tenants WHERE slug=$1', [SLUG]);
  if (!t) throw new Error('tenant not found - run npm run seed && npm run seed:bulk');
  const { rows: [{ n }] } = await pool.query('SELECT COUNT(*)::int n FROM orders'); // owner role; RLS FORCE => may be 0
  const cnt = await withTenant(t.id, async (db) => (await db.query('SELECT COUNT(*)::int n FROM orders WHERE tenant_id=$1', [t.id])).rows[0].n);

  console.log(`Tenant ${SLUG}: ${cnt} orders`);
  await pool.query('DROP INDEX IF EXISTS idx_orders_tenant_created'); await pool.query('ANALYZE orders');
  const before = await explain(t.id);
  console.log('\n=== BEFORE INDEX ===\n' + before.plan + `\nmedian ${before.median} ms`);

  await pool.query('CREATE INDEX idx_orders_tenant_created ON orders (tenant_id, created_at DESC)'); await pool.query('ANALYZE orders');
  const after = await explain(t.id);
  console.log('\n=== AFTER INDEX ===\n' + after.plan + `\nmedian ${after.median} ms`);

  // N+1 vs JOIN
  const rows = [];
  for (const limit of [20, 100, 200]) {
    const a = [], b = [];
    await nPlusOne(t.id, limit); await joined(t.id, limit); // warm-up
    for (let i = 0; i < 5; i++) { a.push((await nPlusOne(t.id, limit))); b.push((await joined(t.id, limit))); }
    rows.push({ limit, nq: a[0].q, nms: median(a.map((x) => x.ms)), jq: 1, jms: median(b.map((x) => x.ms)) });
  }
  console.log('\nN+1 vs JOIN'); console.table(rows);

  const speedup = (before.median / after.median).toFixed(1);
  const md = `# Benchmark results (auto-generated by \`npm run benchmark\`)

Dataset: tenant \`${SLUG}\` has **${cnt.toLocaleString()} orders**. Run at ${new Date().toISOString()}.

## 1. EXPLAIN ANALYZE - before vs after composite index

Query:
\`\`\`sql
${Q.replace(/\s+/g, ' ')}
\`\`\`

### BEFORE (no index on tenant_id, created_at) - median of ${RUNS} runs: **${before.median} ms**
\`\`\`
${before.plan}
\`\`\`

### AFTER \`CREATE INDEX idx_orders_tenant_created ON orders (tenant_id, created_at DESC)\` - median: **${after.median} ms**
\`\`\`
${after.plan}
\`\`\`

| | Execution time (median) | Plan |
|---|---|---|
| Before | ${before.median} ms | Seq Scan + sort |
| After  | ${after.median} ms | Index Scan |
| Speed-up | **${speedup}x** | |

## 2. N+1 vs single JOIN (API layer, includes pool + tenant transaction)

| Orders returned | N+1 queries | N+1 latency | JOIN queries | JOIN latency | Speed-up |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.limit} | ${r.nq} | ${r.nms.toFixed(1)} ms | ${r.jq} | ${r.jms.toFixed(1)} ms | ${(r.nms / r.jms).toFixed(1)}x |`).join('\n')}
`;
  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'benchmark-results.md'), md);
  console.log('\nWrote docs/benchmark-results.md (index kept in place)');
  await pool.end();
})().catch((e) => { console.error(e); process.exit(1); });
